def feat_html(ico, b, s):
    return (
        '<div class="feat"><span class="feat-ico">%s</span><div><b>%s</b>'
        "<span>%s</span></div></div>" % (ico, b, s)
    )


def build(page):
    head = HEAD_TPL.format(title=page["title"], desc=page["desc"])
    feats = "\n      ".join(feat_html(*f) for f in page["features"])
    body = BODY_TPL.format(
        who=page["who"],
        who_lower=page["who"].split()[0].lower() + "ам" if False else page["who"],
        h1=page["h1"],
        lead=page["lead"],
        scenario=page["scenario"],
        features=feats,
        final_h=page["final_h"],
        final_p=page["final_p"],
    )
    html = SHELL
    # заменяем старые метатеги head (вплоть до </head>)
    old_title = html[html.index("<title>") : html.index("</head>")]
    html = html.replace(old_title, head)
    html = html.replace("</head-placeholder>", "</head>", 1)
    # вырезаем тело между </header> и <footer... нет — между hero-wrap началом и footer
    start = html.index('<div class="wrap">\n  <div class="hero"')
    end = html.index("  <footer>")
    html = html[:start] + body.strip("\n") + "\n\n" + html[end:]
    out = BASE / page["slug"]
    out.mkdir(exist_ok=True)
    (out / "index.html").write_text(html, encoding="utf-8")
    return page["slug"]


